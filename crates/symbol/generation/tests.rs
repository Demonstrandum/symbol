#[cfg(unix)]
#[test]
fn wrapper_overrides_hostile_inherited_bump_intent() {
    let root = workspace_root();
    let directory = tempfile::tempdir().unwrap();
    let fake_bin = directory.path().join("bin");
    fs::create_dir(&fake_bin).unwrap();
    let fake_cargo = fake_bin.join("cargo");
    fs::write(
        &fake_cargo,
        "#!/bin/sh\nprintf '%s|%s|%s|%s\\n' \"${SYMBOL_GENERATION_MODE-unset}\" \"${SYMBOL_API_BUMP-unset}\" \"${SYMBOL_API_BUMP_EXPECTED-unset}\" \"${SYMBOL_API_BUMP_TARGET-unset}\" > \"$CAPTURE\"\n",
    )
    .unwrap();
    fs::set_permissions(&fake_cargo, fs::Permissions::from_mode(0o755)).unwrap();
    let inherited_path = std::env::var_os("PATH").unwrap();

    let ledger = read_ledger(&root).unwrap();
    let token = format!(
        "{}:{}:{}",
        ledger.version, ledger.absolute_revision, ledger.source_hash
    );
    let cases = [
        ("update", "update|unset|unset|unset".to_string()),
        ("check", "readonly|unset|unset|unset".to_string()),
        (
            "bump-minor",
            format!("update|minor|{token}|{}", ledger.version.next_minor()),
        ),
        (
            "bump-major",
            format!("update|major|{token}|{}", ledger.version.next_major()),
        ),
    ];
    for (command, expected) in cases {
        let capture = directory.path().join(format!("{command}.txt"));
        let status = Command::new(root.join("api-version"))
            .arg(command)
            .env("SYMBOL_API_BUMP", "hostile-inherited-value")
            .env("CAPTURE", &capture)
            .env(
                "PATH",
                std::env::join_paths(
                    std::iter::once(fake_bin.clone()).chain(std::env::split_paths(&inherited_path)),
                )
                .unwrap(),
            )
            .status()
            .unwrap();
        assert!(status.success(), "{command}");
        assert_eq!(
            fs::read_to_string(capture).unwrap(),
            format!("{expected}\n"),
            "{command}"
        );
    }
}

#[test]
fn unsafe_commits_cannot_reach_javascript_or_python_artifacts() {
    let root = workspace_root();
    for commit in [
        "deadbeef\n// injected",
        "deadbeef\n# injected",
        "deadbeef\";globalThis.pwned=true;//",
        "unknown\nprint('pwned')",
    ] {
        assert!(
            BuildProvenance::from_injected(commit.to_string(), false).is_err(),
            "{commit:?}"
        );
    }

    let ledger = VersionLedger {
        version: ApiVersion::new(2, 3, 4),
        absolute_revision: 57,
        source_hash: canonical_source_hash(&root).unwrap(),
    };
    for commit in ["deadbeef\n// injected", "deadbeef\n# injected"] {
        let metadata = GenerationMetadata {
            ledger: ledger.clone(),
            provenance: BuildProvenance {
                commit: commit.to_string(),
                dirty: false,
            },
        };
        assert!(generate_artifacts(&root, &metadata).is_err(), "{commit:?}");
    }

    let metadata = GenerationMetadata {
        ledger: VersionLedger {
            version: ApiVersion::new(2, 3, 4),
            absolute_revision: 57,
            source_hash: canonical_source_hash(&root).unwrap(),
        },
        provenance: BuildProvenance::from_injected("unknown".to_string(), false).unwrap(),
    };
    let artifacts = generate_artifacts(&root, &metadata).unwrap();
    assert!(artifacts.api_js.contains("\\\"commit\\\":\\\"unknown\\\""));
    assert!(artifacts.api_py.contains("\"commit\":\"unknown\""));
}

