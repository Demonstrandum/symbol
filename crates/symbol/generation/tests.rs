fn runtime_exports(module: &Module) -> BTreeSet<String> {
    let mut names = BTreeSet::new();
    for item in &module.body {
        let ModuleItem::ModuleDecl(ModuleDecl::ExportDecl(export)) = item else {
            continue;
        };
        match &export.decl {
            Decl::Var(variable) => {
                for declarator in &variable.decls {
                    let Pat::Ident(identifier) = &declarator.name else {
                        continue;
                    };
                    names.insert(identifier.id.sym.to_string());
                }
            }
            Decl::Fn(function) => {
                names.insert(function.ident.sym.to_string());
            }
            Decl::Class(class) => {
                names.insert(class.ident.sym.to_string());
            }
            Decl::TsEnum(enumeration) => {
                names.insert(enumeration.id.sym.to_string());
            }
            Decl::TsInterface(_) | Decl::TsTypeAlias(_) | Decl::TsModule(_) | Decl::Using(_) => {}
        }
    }
    names
}

fn header_identity(source: &str) -> HeaderIdentity {
    HeaderIdentity {
        api_version: header_field(source, "API"),
        absolute_revision: header_field(source, "Absolute revision"),
        source_hash: header_field(source, "Source Blake3"),
        generator_version: header_field(source, "Generator version"),
        commit: header_field(source, "Commit"),
        state: header_field(source, "State"),
    }
}

fn header_field(source: &str, field: &str) -> String {
    source
        .lines()
        .map(|line| line.trim_start_matches('/').trim_start_matches('#').trim())
        .find_map(|line| line.strip_prefix(&format!("{field}: ")))
        .unwrap_or_else(|| panic!("missing generated header field {field}"))
        .to_string()
}

fn typecheck_declarations_if_available(declarations: &str) {
    let Ok(version) = Command::new("tsc").arg("--version").output() else {
        return;
    };
    assert!(version.status.success());
    let directory = tempfile::tempdir().unwrap();
    let declaration_path = directory.path().join("symbol.d.ts");
    fs::write(&declaration_path, declarations).unwrap();
    let output = Command::new("tsc")
        .args(["--noEmit", "--strict", "--skipLibCheck", "false"])
        .arg(&declaration_path)
        .current_dir(directory.path())
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
}
