#[test]
fn swc_outputs_have_runtime_export_parity_and_declarations_only() {
    let root = workspace_root();
    let artifacts = generate_artifacts(&root, &test_metadata(&root)).unwrap();

    let typescript = parse_ts_module_for_test(&artifacts.api_ts).unwrap();
    let javascript = parse_es_module_for_test(&artifacts.api_js).unwrap();
    let declarations = parse_ts_module_for_test(&artifacts.api_d_ts).unwrap();
    parse_es_module_for_test(&artifacts.api_global_js).unwrap();

    let expected = runtime_exports(&typescript);
    assert_eq!(runtime_exports(&javascript), expected);
    assert_eq!(runtime_exports(&declarations), expected);
    for required in REQUIRED_RUNTIME_EXPORTS {
        assert!(expected.contains(required), "{required}");
        assert!(
            artifacts
                .api_global_js
                .contains(&format!("get {required} ()")),
            "UMD omitted {required}"
        );
    }
    assert!(!artifacts.api_js.contains("interface SymbolApiMetadata"));
    assert!(!artifacts.api_global_js.contains("export "));
    assert!(artifacts.api_global_js.contains(".SymbolAPI"));

    for item in &declarations.body {
        let ModuleItem::ModuleDecl(ModuleDecl::ExportDecl(export)) = item else {
            continue;
        };
        let Decl::Var(variable) = &export.decl else {
            continue;
        };
        assert!(variable.declare);
        assert!(
            variable
                .decls
                .iter()
                .all(|declarator| declarator.init.is_none())
        );
    }
}

#[test]
fn declarations_cover_exported_types_functions_and_classes() {
    let source = r#"
const hidden = 1;
function helper(): number { return hidden; }
export interface RequestOptions { timeoutMs?: number; }
export type Result<T> = { value: T };
export function request(path: string, options?: RequestOptions): Promise<Result<string>> {
    return Promise.resolve({ value: path });
}
export class Client {
    #secret = 1;
    private token: string = "secret";
    readonly endpoint: string = "https://example.invalid";
    constructor(endpoint: string) { this.endpoint = endpoint; }
    request(path: string): Promise<string> { return Promise.resolve(path); }
    private reset(): void { this.token = ""; }
}
export const DEFAULT_TIMEOUT: number = 30;
"#;
    let declarations = emit_declarations(source, "golden.ts").unwrap();
    let expected = r#"export interface RequestOptions {
    timeoutMs?: number;
}
export type Result<T> = {
    value: T;
};
export declare function request(path: string, options?: RequestOptions): Promise<Result<string>>;
export declare class Client {
    readonly endpoint: string;
    constructor(endpoint: string);
    request(path: string): Promise<string>;
}
export declare const DEFAULT_TIMEOUT: number;
"#;
    assert_eq!(declarations, expected);
    parse_ts_module_for_test(&declarations).unwrap();
    for forbidden in [
        "hidden",
        "helper",
        "#secret",
        "token",
        "reset",
        "Promise.resolve",
        "\"secret\"",
        "\"https://example.invalid\"",
    ] {
        assert!(!declarations.contains(forbidden), "{forbidden}");
    }
}

#[test]
fn declarations_retain_private_type_dependencies_and_strip_namespaces_recursively() {
    let source = r#"
interface WireValue { value: string; }
type WireResult = { result: WireValue };
const runtimeHelper = 1;
export function decode(value: WireValue): WireResult {
    return { result: value };
}
export namespace SDK {
    interface Request { path: string; }
    export function request(input: Request): Promise<Request> {
        return Promise.resolve(input);
    }
    export class Client {
        private token: string = "secret";
        request(input: Request): Promise<Request> { return Promise.resolve(input); }
        private reset(): void { this.token = ""; }
    }
    export namespace Nested {
        export function create(input: Request): Request { return input; }
    }
}
"#;
    let declarations = emit_declarations(source, "namespace-golden.ts").unwrap();
    let expected = r#"interface WireValue {
    value: string;
}
type WireResult = {
    result: WireValue;
};
export declare function decode(value: WireValue): WireResult;
export declare namespace SDK {
    interface Request {
        path: string;
    }
    export function request(input: Request): Promise<Request>;
    export class Client {
        request(input: Request): Promise<Request>;
    }
    export namespace Nested {
        export function create(input: Request): Request;
    }
}
"#;
    assert_eq!(declarations, expected);
    parse_ts_module_for_test(&declarations).unwrap();
    assert!(!declarations.contains("runtimeHelper"));
    for forbidden in ["Promise.resolve", "\"secret\"", "token", "reset", "return "] {
        assert!(!declarations.contains(forbidden), "{forbidden}");
    }
    typecheck_declarations_if_available(&declarations);
}

